export function getYoutubeVideoId(url: string): string {
  const match = url.match(/[?&]v=([a-zA-Z0-9_-]+)/);
  if (match) return match[1];
  const shortMatch = url.match(/youtu\.be\/([a-zA-Z0-9_-]+)/);
  if (shortMatch) return shortMatch[1];
  return '';
}

export function getYoutubeThumbnail(url: string): string {
  const id = getYoutubeVideoId(url);
  return id ? `https://img.youtube.com/vi/${id}/hqdefault.jpg` : '';
}

export function getSongBonusPercent(completedCount: number, isLuckyCompleted: boolean = false): number {
  let percent = 0;
  if (completedCount >= 5) percent = 50;
  else if (completedCount === 4) percent = 30;
  else if (completedCount === 3) percent = 20;
  else if (completedCount === 2) percent = 10;
  else if (completedCount === 1) percent = 5;

  if (isLuckyCompleted) {
    percent += 100;
  }
  return percent;
}

export interface RoundSelection {
  standardSongs: ApinkTrack[];
  luckySong: ApinkTrack;
}

export function pickRoundWithLuckySong(standardCount: number = 5): RoundSelection {
  const shuffled = [...APINK_TRACKS].sort(() => Math.random() - 0.5);
  const standardSongs = shuffled.slice(0, standardCount);
  standardSongs.sort((a, b) => a.letterCount - b.letterCount);
  // The 6th song is picked from the remaining songs outside the first 5
  const luckySong = shuffled[standardCount] ?? shuffled[0];
  return { standardSongs, luckySong };
}

export function pickRoundSongs(count: number = 5): ApinkTrack[] {
  return pickRoundWithLuckySong(count).standardSongs;
}

